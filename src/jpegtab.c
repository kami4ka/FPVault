void jpegtab_quant(int quality, uint16_t qY[64], uint16_t qC[64]) {
    int scale, i, v;
    if(quality < 1) quality = 1;
    if(quality > 100) quality = 100;
    scale = (quality < 50) ? 5000 / quality : 200 - quality * 2;
    for(i = 0; i < 64; i++) {
        v = (k1_luma[i] * scale + 50) / 100;
        qY[i] = (uint16_t)(v < 1 ? 1 : v > 255 ? 255 : v);
        v = (k1_chroma[i] * scale + 50) / 100;
        qC[i] = (uint16_t)(v < 1 ? 1 : v > 255 ? 255 : v);
    }
}

static uint8_t* put_marker(uint8_t* p, uint8_t code, uint16_t seg_len) {
    *p++ = 0xFF;
    *p++ = code;
    *p++ = (uint8_t)(seg_len >> 8);
    *p++ = (uint8_t)seg_len;
    return p;
}

static uint8_t* put_dqt(uint8_t* p, uint8_t id, const uint16_t q[64]) {
    int i;
    p = put_marker(p, 0xDB, 2 + 1 + 64);
    *p++ = id; /* 8-bit precision, table id */
    for(i = 0; i < 64; i++)
        *p++ = (uint8_t)q[zz[i]]; /* zigzag on the wire */
    return p;
}

static uint8_t* put_dht(uint8_t* p, uint8_t tcth, const uint8_t* tab, uint16_t n) {
    uint16_t i;
    p = put_marker(p, 0xC4, 2 + 1 + n);
    *p++ = tcth;
    for(i = 0; i < n; i++)
        *p++ = tab[i];
    return p;
}

uint32_t jpegtab_prefix(uint8_t* dst, const uint16_t qY[64], const uint16_t qC[64]) {
    uint8_t* p = dst;
    *p++ = 0xFF;
    *p++ = 0xD8; /* SOI */
    p = put_dqt(p, 0x00, qY);
    p = put_dqt(p, 0x01, qC);
    p = put_dht(p, 0x00, dht_dc_luma, sizeof(dht_dc_luma));
    p = put_dht(p, 0x10, dht_ac_luma, sizeof(dht_ac_luma));
    p = put_dht(p, 0x01, dht_dc_chroma, sizeof(dht_dc_chroma));
    p = put_dht(p, 0x11, dht_ac_chroma, sizeof(dht_ac_chroma));
    return (uint32_t)(p - dst);
}

uint32_t jpegtab_headers(uint8_t* dst, const uint16_t qY[64], const uint16_t qC[64],
                         uint16_t w, uint16_t h, int samp_2x2) {
    uint8_t* p = dst + jpegtab_prefix(dst, qY, qC);
    /* SOF0: baseline, 8-bit, 3 components, Y sampling 2x2 or 2x1 */
    p = put_marker(p, 0xC0, 2 + 1 + 2 + 2 + 1 + 3 * 3);
    *p++ = 8;
    *p++ = (uint8_t)(h >> 8);
    *p++ = (uint8_t)h;
    *p++ = (uint8_t)(w >> 8);
    *p++ = (uint8_t)w;
    *p++ = 3;
    *p++ = 1;
    *p++ = (uint8_t)(0x20 | (samp_2x2 ? 2 : 1));
    *p++ = 0;
    *p++ = 2;
    *p++ = 0x11;
    *p++ = 1;
    *p++ = 3;
    *p++ = 0x11;
    *p++ = 1;
    /* Three fill bytes (0xFF before a marker is legal padding, T.81
     * B.1.1.2) round the header block to 608 bytes, so the AVI chunk that
     * precedes it by 8 starts 4-byte aligned - the SD driver word-casts
     * transfer buffers and ARM926 silently rotates misaligned loads. */
    *p++ = 0xFF;
    *p++ = 0xFF;
    *p++ = 0xFF;
    /* SOS */
    p = put_marker(p, 0xDA, 2 + 1 + 2 * 3 + 3);
    *p++ = 3;
    *p++ = 1;
    *p++ = 0x00;
    *p++ = 2;
    *p++ = 0x11;
    *p++ = 3;
    *p++ = 0x11;
    *p++ = 0;  /* Ss */
    *p++ = 63; /* Se */
    *p++ = 0;  /* AhAl */
    return (uint32_t)(p - dst);
}
